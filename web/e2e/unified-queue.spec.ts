import {devices, expect, test} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import type {OperationsSnapshot} from '../src/companion/unifiedOperations';

test('real shared queue supports keyboard ordering, stale revision recovery, pause and product download', async ({page, request, browser}, testInfo) => {
  test.setTimeout(60000);
  await page.goto('/');
  await page.setViewportSize({width: 1440, height: 1000});
  await page.getByRole('button', {name: '任务记录', exact: true}).click();
  const queue = page.getByRole('region', {name: '统一任务队列'});
  await expect(queue.getByRole('button', {name: '启动队列'})).toBeVisible();
  const initial: OperationsSnapshot = await (await request.get('/api/v2/operations')).json();
  expect(initial.paused).toBe(true);
  const handles = queue.getByRole('button', {name: /^拖动排序/});
  await expect(handles).toHaveCount(2);
  await handles.first().focus();
  await page.keyboard.press('Space');
  await expect(handles.first()).toHaveAttribute('aria-pressed', 'true');
  await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))));
  await page.keyboard.press('ArrowDown');
  await expect(queue.locator('tr[data-queue-target]')).toHaveCount(1);
  await page.keyboard.press('Enter');
  await expect.poll(async () => {
    const value: OperationsSnapshot = await (await request.get('/api/v2/operations')).json();
    return value.operations.map(item => item.id);
  }).toEqual(initial.operations.map(item => item.id).reverse());
  const second = await page.context().newPage();
  await second.goto('/');
  await second.getByRole('button', {name: '任务记录', exact: true}).click();
  await second.getByText('任务标题与标签', {exact: true}).click();
  await second.getByLabel('任务标题', {exact: true}).fill('另一个窗口的草稿');
  await second.getByLabel('搜索任务').fill('不存在的筛选条件');
  await expect(second.getByText('没有匹配的任务，请调整筛选或创建新任务。')).toBeVisible();
  await second.getByLabel('搜索任务').fill('');
  await second.getByText('任务标题与标签', {exact: true}).click();
  await expect(second.getByLabel('任务标题', {exact: true})).toHaveValue('另一个窗口的草稿');
  await page.getByText('任务标题与标签', {exact: true}).click();
  await page.getByLabel('任务标题', {exact: true}).fill('统一架构浏览器验收');
  await page.getByRole('button', {name: '保存任务信息'}).click();
  await expect(page.getByRole('button', {name: /统一架构浏览器验收/})).toBeVisible();
  await second.getByRole('button', {name: '保存任务信息'}).click();
  await expect(second.getByRole('alert')).toContainText('任务元数据已变化');
  await expect(second.getByLabel('任务标题', {exact: true})).toHaveValue('另一个窗口的草稿');
  await second.close();
  await page.screenshot({path: testInfo.outputPath('desktop-light.png'), fullPage: true});
  await page.setViewportSize({width: 1920, height: 1080});
  await page.screenshot({path: testInfo.outputPath('desktop-wide.png'), animations: 'disabled'});
  await page.setViewportSize({width: 1440, height: 1000});
  let release: (() => void) | undefined;
  const blocked = new Promise<void>(resolve => {release = resolve;});
  let intercepted: (() => void) | undefined;
  const caught = new Promise<void>(resolve => {intercepted = resolve;});
  await page.route('**/api/v2/operations/queue', async route => {intercepted?.(); await blocked; await route.continue();});
  await queue.getByRole('button', {name: '启动队列'}).click();
  await caught;
  const current: OperationsSnapshot = await (await request.get('/api/v2/operations')).json();
  expect((await request.post(`/api/v2/operations/${current.operations[0].id}/waiting`, {data: {state: 'paused'}})).ok()).toBe(true);
  release?.();
  await expect(queue.getByRole('alert')).toContainText('队列状态已变化');
  await page.unroute('**/api/v2/operations/queue');
  await expect(queue.getByRole('button', {name: '排队', exact: true})).toBeVisible();
  await queue.getByRole('button', {name: '排队', exact: true}).click();
  await page.emulateMedia({colorScheme: 'dark', reducedMotion: 'reduce'});
  await page.screenshot({path: testInfo.outputPath('desktop-dark-reduced.png'), fullPage: true});
  const mobile = await browser.newContext({...devices['iPhone 13'], viewport: {width: 390, height: 844}, baseURL: process.env.UNIFIED_QA_URL, reducedMotion: 'reduce'});
  const phone = await mobile.newPage();
  await phone.goto('/');
  await phone.getByRole('button', {name: '任务记录', exact: true}).click();
  await expect(phone.getByRole('region', {name: '统一任务队列'})).toBeVisible();
  await phone.evaluate(() => document.fonts.ready);
  for (const colorScheme of ['light', 'dark'] as const) {
    await phone.emulateMedia({colorScheme});
    await phone.evaluate(() => window.scrollTo(0, 0));
    await phone.screenshot({path: testInfo.outputPath(`phone-${colorScheme}.png`), animations: 'disabled'});
    const bounds = await phone.getByRole('button', {name: /^拖动排序/}).first().boundingBox();
    const title = await phone.getByRole('region', {name: '统一任务队列'}).locator('tbody tr').first().locator('td').nth(1).getByRole('button').boundingBox();
    expect(bounds && title && bounds.x + bounds.width <= title.x).toBe(true);
    await phone.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
    await phone.screenshot({path: testInfo.outputPath(`phone-${colorScheme}-bottom.png`), animations: 'disabled'});
    expect(await phone.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  }
  await mobile.close();
  await queue.getByRole('button', {name: '启动队列'}).click();
  await expect.poll(async () => {
    const value: OperationsSnapshot = await (await request.get('/api/v2/operations')).json();
    return value.operations.map(item => item.state);
  }, {timeout: 30_000}).toEqual(['succeeded', 'succeeded']);
  await expect(queue.getByText('已完成', {exact: true})).toHaveCount(2);
  await queue.getByRole('button', {name: '暂停后续任务'}).click();
  await expect(queue.getByRole('button', {name: '启动队列'})).toBeVisible();
  const jobs: {id: string}[] = await (await request.get('/companion-api/jobs')).json();
  const exports = await (await request.get(`/companion-api/jobs/${jobs[0].id}/subtitle-exports`)).json();
  expect(exports.outputs).toHaveLength(2);
  const product = await request.get(`/companion-api/jobs/${jobs[0].id}/files/${exports.outputs[0].filename}`);
  expect(product.ok()).toBe(true);
  expect(await product.text()).toContain('[Script Info]');
  await page.reload();
  await page.getByRole('button', {name: '任务记录', exact: true}).click();
  await expect(queue.getByRole('button', {name: '启动队列'})).toBeVisible();
  await expect(queue.getByText('已完成', {exact: true})).toHaveCount(2);
  await expect(page.getByLabel('完整视频预览', {exact: true})).toBeVisible();
  await page.screenshot({path: testInfo.outputPath('queue-completed.png'), fullPage: true});
  await page.getByRole('button', {name: '导出', exact: true}).click();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('link', {name: /^下载ASS 字幕/}).first().click();
  const download = await downloadEvent;
  const path = await download.path();
  if (path === null) throw new Error('Browser did not retain the downloaded product');
  expect(await readFile(path, 'utf8')).toContain('[Script Info]');
});

test('real transport polls library during an SSE outage and replays a durable cursor after disconnect', async ({page, request}, testInfo) => {
  test.setTimeout(90000);
  let failures = 0;
  await page.route('**/api/v2/events*', async route => {failures += 1; await route.abort('connectionfailed');});
  await page.goto('/');
  await page.getByRole('button', {name: '任务记录', exact: true}).click();
  await expect.poll(() => failures, {timeout: 25000}).toBeGreaterThanOrEqual(5);
  const library: {items: {task_id:string; version:string}[]} = await (await request.get('/api/v2/library')).json();
  const task = library.items[0];
  expect((await request.patch(`/api/v2/library/${task.task_id}`, {data:{expected_version:task.version, title:'事件断线期间的真实修改'}})).ok()).toBe(true);
  await expect(page.getByRole('button', {name:/事件断线期间的真实修改/})).toBeVisible({timeout:20000});
  await page.screenshot({path:testInfo.outputPath('polling-fallback.png')});
  await page.unroute('**/api/v2/events*');
  await page.waitForResponse(response => response.url().includes('/api/v2/events') && response.status() === 200, {timeout:35000});
  const connected: {items:{task_id:string;version:string}[]} = await (await request.get('/api/v2/library')).json();
  expect((await request.patch(`/api/v2/library/${task.task_id}`, {data:{expected_version:connected.items[0].version, title:'事件连接已恢复'}})).ok()).toBe(true);
  await expect(page.getByRole('button', {name:/事件连接已恢复/})).toBeVisible({timeout:5000});
  const reconnect = page.waitForRequest(req => req.url().includes('/api/v2/events') && new URL(req.url()).searchParams.has('cursor'));
  expect((await request.post('/qa/disconnect-events')).ok()).toBe(true);
  const current: {items:{task_id:string;version:string}[]} = await (await request.get('/api/v2/library')).json();
  expect((await request.patch(`/api/v2/library/${task.task_id}`, {data:{expected_version:current.items[0].version, title:'事件游标重连后的真实修改'}})).ok()).toBe(true);
  expect(Number(new URL((await reconnect).url()).searchParams.get('cursor'))).toBeGreaterThan(0);
  await expect(page.getByRole('button', {name:/事件游标重连后的真实修改/})).toBeVisible({timeout:10000});
});
